const EDITIONS = ["1st Edition", "2nd Edition", "3rd Edition", "4th Edition", "5th Edition", "6th Edition", "7th Edition", "8th Edition", "Global Edition", "Indian Edition", "Revised Edition", "Special Edition"];

function pseudoRandom(seed: number): number {
  const x = Math.sin(seed) * 10000;
  return x - Math.floor(x);
}

// Build the full seed list of real + generated books, ensuring 1000+ entries.
export function buildSeedBooks(): Book[] {
  const books: Book[] = [];
  const seen = new Set<string>();

  const addBook = (title: string, author: string, category: string, status: BookStatus) => {
    const key = `${title}|${author}`;
    if (seen.has(key)) return;
    seen.add(key);
    books.push({
      id: `BK${String(books.length + 1).padStart(5, "0")}`,
      title,
      author,
      category,
      status,
    });
  };

  // First insert the curated real titles.
  SEED_BOOKS.forEach((b, i) => {
    addBook(b.title, b.author, b.category, i % 4 === 0 ? "Issued" : "Available");
  });

  // Then generate enough additional books to exceed 1000 total entries.
  const allCats = Object.keys(TITLE_TOPICS);
  let seed = 1;
  while (books.length < 1050) {
    const cat = allCats[Math.floor(pseudoRandom(seed) * allCats.length)];
    const prefix = TITLE_PREFIXES[Math.floor(pseudoRandom(seed + 1) * TITLE_PREFIXES.length)];
    const topic = TITLE_TOPICS[cat][Math.floor(pseudoRandom(seed + 2) * TITLE_TOPICS[cat].length)];
    const author = CATEGORY_AUTHORS[cat][Math.floor(pseudoRandom(seed + 3) * CATEGORY_AUTHORS[cat].length)];
    const edition = EDITIONS[Math.floor(pseudoRandom(seed + 4) * EDITIONS.length)];
    addBook(`${prefix} ${topic}, ${edition}`, author, cat, pseudoRandom(seed + 5) > 0.7 ? "Issued" : "Available");
    seed += 6;
  }

  return books;
}
